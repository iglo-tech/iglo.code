class ForkIdentityTest(unittest.TestCase):
    def test_reports_upstream_runtime_names_and_ignores_internal_ones(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            files = {
                "apps/server/src/config.ts": 'const home = join(homedir(), ".t3");\nprocess.env.T3CODE_PORT;\n',
                "apps/server/src/refs.ts": 'const prefix = "refs/t3/checkpoints";\n',
                "apps/server/src/fine.ts": 'import { x } from "@t3tools/shared";\nconst T3_PROJECT_FILE_NAME = "iglo.code.json";\n'
                                           'const url = "https://app.t3.codes";\nprocess.env.T3_ACP_FAIL_PROMPT;\n',
                "docs/user/install.md": "Run `t3 serve` or the desktop app.\n",
                "docs/internals/notes.md": "Upstream T3 Code has a desktop app.\n",
            }
            for path, text in files.items():
                (root / path).parent.mkdir(parents=True, exist_ok=True)
                (root / path).write_text(text)
            labels = sorted({(path, label) for path, _, label, _ in check(root, list(files))})
            self.assertEqual(labels, [
                ("apps/server/src/config.ts", "env var T3CODE_*"),
                ("apps/server/src/config.ts", "~/.t3 or worktree .t3 path"),
                ("apps/server/src/refs.ts", "git ref refs/t3"),
                ("docs/user/install.md", "desktop or mobile app"),
                ("docs/user/install.md", "t3 CLI command"),
            ])

