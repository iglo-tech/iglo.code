const dedent = (text: string) => {
  const lines = text.replace(/^\n+/, "").split("\n");
  const indent = Math.min(
    ...lines.filter((line) => line.trim()).map((line) => line.length - line.trimStart().length),
  );
  return lines.map((line) => (line.trim() ? line.slice(indent) : "")).join("\n");
};

const tempDir = () => {
  const dir = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "sync-upstream-test-"));
  return { dir, [Symbol.dispose]: () => NodeFS.rmSync(dir, { recursive: true, force: true }) };
};

const checkout = () => {
  const temp = tempDir();
  const root = NodePath.join(temp.dir, "fork");
  const at = (path: string) => NodePath.join(root, path);
  const write = (path: string, text: string) => {
    NodeFS.mkdirSync(NodePath.dirname(at(path)), { recursive: true });
    NodeFS.writeFileSync(at(path), dedent(text));
  };
  const read = (path: string) => NodeFS.readFileSync(at(path), "utf8");
  const exists = (path: string) =>
    NodeFS.lstatSync(at(path), { throwIfNoEntry: false }) !== undefined;
  write("apps/web/package.json", '{"name":"web"}\n');
  write(
    "package.json",
    JSON.stringify({
      name: "fork",
      scripts: {
        dev: "node scripts/dev-runner.ts",
        "lint:mobile": "node scripts/mobile-native-static-check.ts",
        "icons:export:android": "node scripts/export-android-icons.ts",
        "build:marketing": "vp run --filter @t3tools/marketing build",
      },
    }),
  );
  return { temp, root, at, write, read, exists, [Symbol.dispose]: temp[Symbol.dispose] };
};

